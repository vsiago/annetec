import type { LucideIcon } from 'lucide-react'
import type { ReactNode } from 'react'
import { Card, CardContent } from '@/components/ui/card'
import { cn } from '@/lib/utils'

// Shown wherever a freshly-created tenant has no records yet. A new club
// should see an honest, actionable empty state — never invented sample data.
export function EmptyState({
  icon: Icon,
  title,
  description,
  action,
  className,
}: {
  icon?: LucideIcon
  title: string
  description?: string
  action?: ReactNode
  className?: string
}) {
  return (
    <div className={cn('flex flex-col items-center justify-center px-6 py-12 text-center', className)}>
      {Icon && (
        <div className="mb-4 rounded-full bg-muted p-3">
          <Icon className="h-6 w-6 text-muted-foreground" />
        </div>
      )}
      <h3 className="font-semibold text-foreground">{title}</h3>
      {description && <p className="mt-1 max-w-sm text-sm text-muted-foreground">{description}</p>}
      {action && <div className="mt-4">{action}</div>}
    </div>
  )
}

/** EmptyState wrapped in the standard card shell, for full-width slots. */
export function EmptyStateCard(props: Parameters<typeof EmptyState>[0]) {
  return (
    <Card className="border-0 shadow-sm">
      <CardContent className="p-0">
        <EmptyState {...props} />
      </CardContent>
    </Card>
  )
}
